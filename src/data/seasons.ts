// ============================================================================
// HELPERS - Funções para usar os dados
// ============================================================================

export function getSeasonByNumber(number: number): Season | undefined {
  return SEASONS.find(s => s.number === number);
}

export function getSeasonsByPhase(phase: Phase): Season[] {
  return SEASONS.filter(s => s.phase === phase);
}

export function getTotalModules(): number {
  return SEASONS.reduce((acc, s) => acc + s.modules, 0);
}

export function getSeasonSummary(seasonNumber: number): string {
  const season = getSeasonByNumber(seasonNumber);
  if (!season) return 'Temporada não encontrada';
  
  const phase = season.phase;
  const phaseInfo = {
    DESPERTAR: 'Fase 1/5 - Despertar',
    TENSÃO: 'Fase 2/5 - Tensão', 
    RUPTURA: 'Fase 3/5 - Ruptura',
    CONVERGÊNCIA: 'Fase 4/5 - Convergência',
    TRANSCENDÊNCIA: 'Fase 5/5 - Transcendência',
  };
  
  return `${phaseInfo[phase]} · ${season.title} · ${season.modules} módulos`;
}